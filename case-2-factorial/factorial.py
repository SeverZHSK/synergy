"""
Кейс-задача №2. Программа вычисления факториала числа.

Функциональность:
1. Запрашивает у пользователя положительное целое число.
2. Вычисляет факториал (реализована собственная функция + оптимизированный
   вариант на основе стандартной библиотеки math).
3. Выводит результат на экран.
4. Обрабатывает ошибки ввода: нечисловые данные, отрицательные числа,
   дробные числа, пустой ввод.
5. Для больших чисел использует math.factorial (реализован на C и работает
   значительно быстрее, чем цикл на чистом Python) и сравнивает время работы
   обеих реализаций.

Автор: практикант, направление "Информационные системы и технологии",
профиль "Тестирование и DevOps".
"""

import math
import time


def get_positive_integer(prompt: str = "Введите положительное целое число: ") -> int:
    """
    Запрашивает у пользователя ввод и возвращает положительное целое число.

    Повторяет запрос до тех пор, пока не будет введено корректное значение.
    Обрабатывает следующие ошибки:
        - ValueError: введена строка, дробное число или пустая строка;
        - собственная проверка: введено отрицательное число или ноль
          (в зависимости от требований ноль можно считать допустимым,
           здесь 0! = 1 разрешён, а отрицательные числа — нет).
    """
    while True:
        raw_value = input(prompt).strip()
        try:
            value = int(raw_value)
        except ValueError:
            print(
                f'Ошибка: "{raw_value}" не является целым числом. '
                "Повторите ввод (например: 5)."
            )
            continue

        if value < 0:
            print("Ошибка: число не может быть отрицательным. Повторите ввод.")
            continue

        return value


def factorial_manual(n: int) -> int:
    """
    Собственная (неоптимизированная) реализация факториала — простой цикл.

    Используется как базовая, «учебная» реализация и как эталон для
    сравнения производительности с оптимизированным вариантом.
    """
    result = 1
    for i in range(2, n + 1):
        result *= i
    return result


def factorial_optimized(n: int) -> int:
    """
    Оптимизированная реализация факториала на основе стандартной
    библиотеки math.

    math.factorial реализована на языке C внутри интерпретатора CPython,
    поэтому для больших чисел (сотни и тысячи) она работает существенно
    быстрее собственной реализации на чистом Python и является
    рекомендуемым способом вычисления факториала в реальных проектах.
    """
    return math.factorial(n)


def compare_performance(n: int) -> None:
    """Сравнивает время выполнения ручной и оптимизированной реализаций."""
    start = time.perf_counter()
    manual_result = factorial_manual(n)
    manual_time = time.perf_counter() - start

    start = time.perf_counter()
    optimized_result = factorial_optimized(n)
    optimized_time = time.perf_counter() - start

    assert manual_result == optimized_result, "Результаты реализаций не совпадают!"

    print("\n--- Сравнение производительности ---")
    print(f"Собственная реализация:      {manual_time:.6f} сек.")
    print(f"math.factorial (оптимизир.): {optimized_time:.6f} сек.")


def main() -> None:
    print("Программа вычисления факториала числа")
    print("=" * 45)

    n = get_positive_integer()

    result = factorial_optimized(n)

    # Для очень больших чисел не печатаем результат целиком, чтобы не
    # засорять консоль десятками тысяч цифр, а показываем длину числа.
    digits = len(str(result))
    if digits <= 50:
        print(f"\n{n}! = {result}")
    else:
        print(f"\n{n}! содержит {digits} цифр.")
        print(f"Первые 30 цифр: {str(result)[:30]}...")
        print(f"Последние 30 цифр: ...{str(result)[-30:]}")

    if n >= 200:
        compare_performance(n)


if __name__ == "__main__":
    main()
